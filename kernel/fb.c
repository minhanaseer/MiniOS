void fb_draw_char(char c, uint32_t x, uint32_t y,
                  uint8_t r, uint8_t g, uint8_t b) {
    if ((unsigned char)c >= 128) return;
    for (int row = 0; row < 8; row++) {
        unsigned char bits = font[(unsigned char)c][row];
        for (int col = 0; col < 8; col++) {
            if (bits & (0x80 >> col))
                fb_put_pixel(x+col, y+row, r, g, b);
        }
    }
}

void fb_draw_text(const char* s, uint32_t x, uint32_t y,
                  uint8_t r, uint8_t g, uint8_t b) {
    uint32_t cx = x;
    for (int i = 0; s[i]; i++) {
        if (s[i] == '\n') { y += 10; cx = x; continue; }
        fb_draw_char(s[i], cx, y, r, g, b);
        cx += 9;
    }
}
