typedef unsigned int   uint32_t;
typedef unsigned char  uint8_t;

static uint32_t* fb_addr   = 0;
static uint32_t  fb_width  = 0;
static uint32_t  fb_height = 0;
static uint32_t  fb_pitch  = 0;

void fb_init(uint32_t* addr, uint32_t w, uint32_t h, uint32_t pitch) {
    fb_addr   = addr;
    fb_width  = w;
    fb_height = h;
    fb_pitch  = pitch;
}

void fb_put_pixel(uint32_t x, uint32_t y, uint8_t r, uint8_t g, uint8_t b) {
    if (x >= fb_width || y >= fb_height) return;
    uint32_t colour = ((uint32_t)r << 16) | ((uint32_t)g << 8) | b;
    uint32_t offset = y * (fb_pitch / 4) + x;
    fb_addr[offset] = colour;
}

void fb_draw_rect(uint32_t x, uint32_t y, uint32_t w, uint32_t h,
                  uint8_t r, uint8_t g, uint8_t b) {
    for (uint32_t row = y; row < y+h; row++)
        for (uint32_t col = x; col < x+w; col++)
            fb_put_pixel(col, row, r, g, b);
}

void fb_clear(uint8_t r, uint8_t g, uint8_t b) {
    fb_draw_rect(0, 0, fb_width, fb_height, r, g, b);
}

